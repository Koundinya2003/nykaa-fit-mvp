const VIEWS: ProductImage['view'][] = ['front', 'back', 'detail', 'styled'];

const VIEW_LABEL: Record<ProductImage['view'], string> = {
  front: 'front view',
  back: 'back view',
  detail: 'fabric detail',
  styled: 'styled on model',
};

/** One shot per view, per colourway — the gallery filters by selected colour. */
function buildImages(raw: Raw): ProductImage[] {
  return raw.colors.flatMap((colorKey) => {
    const colorName = COLOR_LABEL[colorKey];
    return VIEWS.map((view) => ({
      id: `${raw.id}-${colorKey}-${view}`,
      colorName,
      view,
      alt: `${raw.brand} ${raw.name} in ${colorName} — ${VIEW_LABEL[view]}`,
    }));
  });
}

/** Detail bullets shown on the PDP, assembled so they can never contradict
 *  the structured fields they are built from. */
function buildDetails(raw: Raw): string[] {
  return [
    ...Object.entries(raw.attrs).map(([label, value]) => `${label}: ${value}`),
    `Fit: ${raw.fit}`,
    `Material: ${raw.material}`,
    `Wash Care: ${raw.subcategory === 'shoes' ? 'Wipe with a clean, dry cloth' : 'Machine wash cold, do not bleach'}`,
    'Country of Origin: India',
  ];
}

/** Nykaa Fit is deliberately scoped to women's dresses for this experiment
 *  (see the feature's eligibility module). Sizing metadata is therefore only
 *  attached where the feature can use it, which keeps the opt-in explicit. */
function sizingMetadata(raw: Raw) {
  if (raw.subcategory !== 'dresses' || raw.gender !== 'women') return {};
  return {
    sizeChart: buildSizeChart(raw.brand, raw.sizes),
    brandSizing: getBrandSizing(raw.brand),
  };
}

function toProduct(raw: Raw): Product {
  const soldOutSizes = raw.soldOut ?? [];
  const allSoldOut = soldOutSizes.length >= raw.sizes.length;
  return {
    id: raw.id,
    brand: raw.brand,
    name: raw.name,
    category: raw.category,
    subcategory: raw.subcategory,
    gender: raw.gender,
    price: raw.price,
    mrp: raw.mrp,
    discount: Math.round(((raw.mrp - raw.price) / raw.mrp) * 100),
    rating: raw.rating,
    reviewCount: raw.reviewCount,
    images: buildImages(raw),
    colors: raw.colors.map((key) => ({ name: COLOR_LABEL[key], hex: C[key] })),
    sizes: raw.sizes,
    soldOutSizes,
    description: raw.description,
    details: buildDetails(raw),
    material: raw.material,
    fit: raw.fit,
    fitClass: toFitClass(raw.fit),
    ...sizingMetadata(raw),
    availability: allSoldOut ? 'out-of-stock' : (raw.availability ?? 'in-stock'),
    tags: raw.tags ?? [],
    addedOn: raw.addedOn,
  };
}

export const PRODUCTS: Product[] = RAW.map(toProduct);

const BY_ID = new Map(PRODUCTS.map((p) => [p.id, p]));

export function getProductById(id: string | undefined): Product | undefined {
  return id ? BY_ID.get(id) : undefined;
}

